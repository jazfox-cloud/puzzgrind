import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const root = process.cwd();
const source = resolve(root, "data/lexi/esdb-valid-guesses.txt");
const target = resolve(root, "lib/lexi/server/valid-guesses.generated.ts");
const words = readFileSync(source, "utf8").trim().split(/\r?\n/u);
if (words.length !== 5_097 || words.some((word) => !/^[a-z]{5}$/u.test(word))) {
  throw new Error("The pinned Lexi valid-guess source failed validation.");
}
const output = `// Generated by scripts/generate-lexi-server-lexicon.mjs. Do not import from Client Components.\n` +
  `const words = ${JSON.stringify(words)} as const;\n` +
  `export const VALID_LEXI_GUESS_COUNT = words.length;\n` +
  `export const validLexiGuesses: ReadonlySet<string> = new Set(words);\n`;
writeFileSync(target, output);
